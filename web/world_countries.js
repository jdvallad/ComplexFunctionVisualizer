  function lonLatToStereo(lonDeg, latDeg) {
    const lon = (lonDeg * Math.PI) / 180;
    const lat = (Math.max(-87.5, Math.min(87.5, latDeg)) * Math.PI) / 180;
    const r = Math.cos(lat) / Math.max(1e-4, 1 - Math.sin(lat));
    return { x: r * Math.sin(lon), y: r * Math.cos(lon) };
  }

  function geoPoly(pairs, subdiv = 2) {
    const out = [];
    for (let i = 0; i < pairs.length; i++) {
      const a = pairs[i];
      out.push(lonLatToStereo(a[0], a[1]));
      if (i + 1 < pairs.length && subdiv > 1) {
        const b = pairs[i + 1];
        for (let k = 1; k < subdiv; k++) {
          const t = k / subdiv;
          out.push(lonLatToStereo(a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t));
        }
      }
    }
    return out;
  }

