  function linePts(x0, y0, x1, y1, steps = 160) {
    const pts = [];
    for (let i = 0; i <= steps; i++) {
      const t = i / steps;
      pts.push({ x: x0 + (x1 - x0) * t, y: y0 + (y1 - y0) * t });
    }
    return pts;
  }

  function circlePts(cx, cy, r, n = 72, ccw = true) {
    const pts = [];
    const d = ccw ? 1 : -1;
    for (let i = 0; i < n; i++) {
      const a = d * (i / n) * Math.PI * 2;
      pts.push({ x: cx + r * Math.cos(a), y: cy + r * Math.sin(a) });
    }
    return pts;
  }

  function rectPts(x0, y0, x1, y1) {
    return [
      { x: x0, y: y0 },
      { x: x1, y: y0 },
      { x: x1, y: y1 },
      { x: x0, y: y1 },
    ];
  }

  function arcPts(cx, cy, r, a0, a1, n = 64) {
    const pts = [];
    for (let i = 0; i <= n; i++) {
      const a = a0 + (a1 - a0) * (i / n);
      pts.push({ x: cx + r * Math.cos(a), y: cy + r * Math.sin(a) });
    }
    return pts;
  }

  function wavyPts(x0, y0, x1, y1, amp, n = 64) {
    const pts = [];
    const dx = x1 - x0, dy = y1 - y0, len = Math.hypot(dx, dy) || 1;
    const nx = -dy / len, ny = dx / len;
    for (let i = 0; i <= n; i++) {
      const t = i / n;
      const w = Math.sin(t * Math.PI) * Math.sin(t * Math.PI * 3) * amp;
      pts.push({ x: x0 + dx * t + nx * w, y: y0 + dy * t + ny * w });
    }
    return pts;
  }

